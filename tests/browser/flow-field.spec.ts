import { test, expect } from "@playwright/test";

test("shared flow fields work with ORCA, expose reuse, and survive resets, map changes and results", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.locator("#setup-routing").selectOption("flow-field");
  await page.locator("#setup-movement").selectOption("orca");
  await page.locator("#edit-before-start").click();
  await expect(page.locator("#routing")).toHaveValue("flow-field");
  const snapshot = () => page.locator("#world").evaluate(c => (c as HTMLCanvasElement).toDataURL());
  const initial = await snapshot();
  await page.locator("#start").click();
  await expect.poll(async () => Number(await page.locator("#metric-route-requests").innerText())).toBeGreaterThanOrEqual(100);
  await page.locator("#pause").click();
  await expect(page.locator("#status")).toHaveText("Paused");
  const requests = Number(await page.locator("#metric-route-requests").innerText());
  const builds = Number(await page.locator("#metric-route-searches").innerText());
  expect(builds).toBeGreaterThan(0);
  expect(builds).toBeLessThan(requests);
  await page.getByRole("button", { name: "Block Exit A", exact: true }).click();
  await expect(page.locator("#exit-message")).toContainText("blocked");
  await page.locator("#reset").click();
  await expect(page.locator("#routing")).toHaveValue("flow-field");
  await expect(page.locator("#movement")).toHaveValue("orca");
  await expect(page.locator("#metric-route-searches")).toHaveText("0");
  await expect.poll(snapshot).toBe(initial);
  await page.locator("#routing").selectOption("congestion");
  await expect.poll(snapshot).toBe(initial);
  await page.locator("#routing").selectOption("flow-field");
  await page.locator("#map").selectOption("mvp");
  await expect(page.locator("#routing")).toHaveValue("flow-field");
  await page.locator("#simulation-screen [data-menu]").click();
  await expect(page.locator("#setup-routing")).toHaveValue("flow-field");
  await page.locator("#setup-map").selectOption("stadium");
  await page.locator("#setup-launch").click();
  await page.locator("#stadium-screen [data-menu]").click();
  await page.locator("#setup-map").selectOption("mvp");
  await expect(page.locator("#setup-routing")).toHaveValue("flow-field");
  await page.locator("#setup-population").fill("1");
  await page.locator("#setup-launch").click();
  await expect(page.locator("#results-screen")).toBeVisible({ timeout: 60000 });
  await expect(page.locator("#result-context")).toContainText("Shared Flow Field");
  await expect(page.locator("#result-context")).toContainText("ORCA");
  await expect(page.locator("#result-evacuated")).toHaveText("1 / 1");
  await page.locator("#run-again").click();
  await expect(page.locator("#routing")).toHaveValue("flow-field");
  expect(errors).toEqual([]);
});

