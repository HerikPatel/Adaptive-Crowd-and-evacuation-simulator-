import { test, expect } from "@playwright/test";

test("stadium layers, feature inspection, keyboard selection, pan and zoom", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  // Invalid grid settings must not prevent opening the independent stadium simulation.
  await page.locator("#setup-population").fill("");
  await page.locator("#setup-map").selectOption("stadium");
  await expect(page.getByRole("button", { name: "Start experiment", exact: true })).toHaveCount(0);
  await expect(page.locator("#setup-population")).toBeDisabled();
  await expect(page.locator("#edit-before-start")).toBeHidden();
  await page.getByRole("button", { name: "Open stadium" }).click();
  await expect(page.locator("#stadium-screen")).toBeVisible();
  await expect(page.locator("#stadium-heading")).toBeFocused();
  await expect(page.locator("#simulation-screen")).toBeHidden();
  const details = page.locator("#stadium-feature-details");
  await page.getByRole("button", { name: "Section 101", exact: true }).click();
  await expect(details).toContainText("Lower seating bowl");
  await expect(details).toContainText("Unknown");
  await expect(details.getByRole("link", { name: "Rutgers stadium map" })).toHaveAttribute("href", /scarletknights.com/);
  await page.screenshot({ path: info.outputPath("stadium-overview.png"), fullPage: true });
  await page.getByRole("button", { name: "200 level", exact: true }).click();
  await expect(page.locator('[data-feature="section-101"]')).toBeHidden();
  await expect(page.getByRole("button", { name: "Section 217", exact: true })).toBeVisible();
  await expect(page.locator('[data-feature="gate-west"]')).toBeHidden();
  const picker = page.getByLabel("Inspect a section, gate or connection");
  await expect(picker).toHaveValue("");
  await picker.selectOption("ramp-east");
  await expect(details).toContainText("East upper deck");
  await expect(details).toContainText("Concourse");
  await expect(details).toContainText("PROPOSED CONNECTION");
  await page.getByLabel("Proposed connections", { exact: true }).uncheck();
  await expect(page.locator('[data-feature="ramp-east"]')).toBeHidden();
  await expect(picker).toHaveValue("");
  await page.getByLabel("Proposed connections", { exact: true }).check();
  const section = page.getByRole("button", { name: "Section 201", exact: true });
  await section.focus();
  await page.keyboard.press("Enter");
  await expect(section).toBeFocused();
  await expect(section).toHaveAttribute("aria-pressed", "true");
  await expect(details).toContainText("West upper deck");
  await page.getByLabel("Section labels", { exact: true }).uncheck();
  await expect(section.locator("text")).toBeHidden();
  await page.getByLabel("Section labels", { exact: true }).check();
  await page.getByRole("button", { name: "Concourse & gates", exact: true }).click();
  await picker.selectOption("gate-west");
  await expect(details).toContainText("A, B");
  await expect(page.locator('[data-feature="section-201"]')).toBeHidden();
  await page.getByRole("button", { name: "Overview", exact: true }).click();
  const svg = page.locator("#stadium-map");
  const original = await svg.getAttribute("viewBox");
  await page.getByRole("button", { name: "Zoom in", exact: true }).click();
  await expect(page.locator("#stadium-zoom-value")).toHaveText("150%");
  const zoomed = await svg.getAttribute("viewBox");
  expect(zoomed).not.toBe(original);
  await svg.scrollIntoViewIfNeeded();
  const bounds = (await svg.boundingBox())!;
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width / 2 + 70, bounds.y + bounds.height / 2 + 30, { steps: 5 });
  await page.mouse.up();
  expect(await svg.getAttribute("viewBox")).not.toBe(zoomed);
  await page.getByRole("button", { name: "Fit map", exact: true }).click();
  await expect(svg).toHaveAttribute("viewBox", original!);
  await expect(page.getByRole("button", { name: "Zoom out", exact: true })).toBeDisabled();
  expect(errors).toEqual([]);
});

test("mobile map inspection preserves draft experiment settings and can return to simulation", async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await page.locator("#setup-population").fill("237");
  await page.locator("#setup-routing").selectOption("shortest");
  await page.locator("#setup-map").selectOption("stadium");
  await page.screenshot({ path: info.outputPath("stadium-map-choice-mobile.png"), fullPage: true });
  await page.getByRole("button", { name: "Open stadium" }).click();
  await page.getByRole("button", { name: "100 level", exact: true }).click();
  await page.getByLabel("Inspect a section, gate or connection").selectOption("elevator-138");
  await expect(page.locator("#stadium-feature-details")).toContainText("Unspecified");
  await expect(page.locator("#stadium-feature-details")).toContainText("Reference only");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("stadium-mobile.png"), fullPage: true });
  await page.getByRole("button", { name: "Back to setup", exact: true }).click();
  await expect(page.locator("#menu-heading")).toBeFocused();
  await expect(page.locator("#setup-population")).toHaveValue("237");
  await expect(page.locator("#setup-routing")).toHaveValue("shortest");
  await expect(page.locator("#setup-map")).toHaveValue("stadium");
  await page.locator("#setup-map").selectOption("mvp");
  await expect(page.locator("#setup-population")).toBeEnabled();
  await page.getByRole("button", { name: "Edit layout first", exact: true }).click();
  await expect(page.locator("#simulation-screen")).toBeVisible();
  await expect(page.locator("#status")).toHaveText("Ready");
  await expect(page.locator("#metric-remaining")).toHaveText("237");
  // The same map choice is available in a run; viewing it pauses without resetting.
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await expect.poll(async () => parseFloat(await page.locator("#metric-elapsed").innerText())).toBeGreaterThan(0);
  await page.locator("#map").selectOption("stadium");
  await expect(page.locator("#stadium-screen")).toBeVisible();
  await expect(page.locator("#status")).toHaveText("Paused");
  const pausedTime = await page.locator("#metric-elapsed").innerText();
  await page.getByRole("button", { name: "Back to setup", exact: true }).click();
  await expect(page.locator("#setup-map")).toHaveValue("mvp");
  await expect(page.locator("#setup-population")).toHaveValue("237");
  await expect(page.locator("#setup-routing")).toHaveValue("shortest");
  await expect(page.locator("#metric-elapsed")).toHaveText(pausedTime);
});
