import { test, expect } from "@playwright/test";

test("stadium routes connect levels, apply transfer assumptions and report closures", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.locator("#setup-map").selectOption("stadium");
  await page.getByRole("button", { name: "Open stadium" }).click();
  const connectivity = page.locator("#stadium-connectivity");
  const status = page.locator("#stadium-route-status");
  const features = page.getByLabel("Inspect a section, gate or connection");
  await expect(connectivity).toContainText("72 / 72");
  await expect(status).toContainText("Section 217");
  await expect(page.locator('[data-route-edge="ramp-east"]')).toBeVisible();
  await page.getByRole("button", { name: "200 level", exact: true }).click();
  await features.selectOption("ramp-east");
  await page.getByRole("button", { name: "Close connection", exact: true }).click();
  await expect(connectivity).toContainText("58 / 72");
  await expect(status).toContainText("No route");
  await expect(page.locator("#stadium-active-route path")).toHaveCount(0);
  await expect(page.locator("#stadium-disconnected")).toContainText("217");
  await expect(page.locator('[data-feature="ramp-east"]')).toHaveClass(/is-closed/);
  await page.getByRole("button", { name: "Reopen connection", exact: true }).click();
  await page.getByLabel("Assumed travel time (seconds)", { exact: true }).fill("90");
  await page.getByLabel("Assumed capacity (people/second)", { exact: true }).fill("0.5");
  await page.getByRole("button", { name: "Apply connection settings" }).click();
  await expect(page.locator("#stadium-transfer-message")).toContainText("applied");
  await expect(page.locator("#stadium-route-measures")).toContainText("transfers 90.0 s");
  await page.getByText("Route steps", { exact: true }).click();
  await expect(page.locator("#stadium-route-steps")).toContainText("0.5 people/s");
  await page.getByRole("button", { name: "Overview", exact: true }).click();
  await page.screenshot({ path: info.outputPath("stadium-connected-route.png"), fullPage: true });
  await page.getByLabel("Route start section", { exact: true }).selectOption("section-201");
  await expect(page.locator('[data-route-edge="ramp-west"]')).toBeVisible();
  await expect(page.locator('[data-route-edge="ramp-east"]')).toHaveCount(0);
  await page.getByRole("button", { name: "Reset route assumptions" }).click();
  await features.selectOption("ramp-east");
  await expect(page.getByLabel("Assumed travel time (seconds)", { exact: true })).toHaveValue("30");
  await expect(page.getByLabel("Assumed capacity (people/second)", { exact: true })).toHaveValue("2");
  await page.getByLabel("Destination gate", { exact: true }).selectOption("gate-west");
  await features.selectOption("gate-west");
  await page.getByRole("button", { name: "Close gate group", exact: true }).click();
  await expect(status).toContainText("No route");
  await expect(connectivity).toContainText("72 / 72");
  await page.getByLabel("Destination gate", { exact: true }).selectOption("any");
  await expect(status).not.toContainText("No route");
  await expect(page.locator('[data-route-edge="gate-west"]')).toHaveCount(0);
  for (const gate of ["gate-north", "gate-east", "gate-south"]) {
    await features.selectOption(gate);
    await page.getByRole("button", { name: "Close gate group", exact: true }).click();
  }
  await expect(connectivity).toHaveText("0 / 72 sections can reach an open gate");
  await expect(status).toContainText("No route");
  await page.getByRole("button", { name: "Reset route assumptions" }).click();
  await expect(connectivity).toContainText("72 / 72");
  await expect(status).not.toContainText("No route");
  expect(errors).toEqual([]);
});

test("mobile route controls preserve connectivity while viewing individual layers", async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await page.locator("#setup-map").selectOption("stadium");
  await page.getByRole("button", { name: "Open stadium" }).click();
  await page.getByLabel("Route start section", { exact: true }).selectOption("section-201");
  await page.getByLabel("Destination gate", { exact: true }).selectOption("gate-east");
  const routeText = await page.locator("#stadium-route-measures").innerText();
  await page.getByRole("button", { name: "200 level", exact: true }).click();
  await expect(page.locator("#stadium-route-layer-note")).toContainText("Only this layer");
  await expect(page.locator('[data-route-edge="gate-east"]')).toHaveCount(0);
  await expect(page.locator('[data-route-edge="ramp-west"]')).toBeVisible();
  await page.getByLabel("Show walkable routes", { exact: true }).uncheck();
  await expect(page.locator("#stadium-network path")).toHaveCount(0);
  await expect(page.locator('[data-route-edge="ramp-west"]')).toBeVisible();
  await page.getByLabel("Proposed connections", { exact: true }).uncheck();
  await expect(page.locator("#stadium-route-measures")).toHaveText(routeText);
  await page.getByRole("button", { name: "Concourse & gates", exact: true }).click();
  await expect(page.locator('[data-route-edge="gate-east"]')).toBeVisible();
  await expect(page.locator("#stadium-route-measures")).toHaveText(routeText);
  await expect(page.locator("#stadium-connectivity")).toContainText("72 / 72");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("stadium-route-mobile.png"), fullPage: true });
});
