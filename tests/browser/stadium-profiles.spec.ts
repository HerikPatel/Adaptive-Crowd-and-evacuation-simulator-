import { test, expect } from "@playwright/test";

test("individual profiles can be inspected and edited; uniform comparison resets reproducibly", async ({ page }, info) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await page.goto("/");
  await page.locator("#setup-map").selectOption("stadium");
  await page.getByRole("button", { name: "Open stadium", exact: true }).click();
  await expect(page.getByLabel("Crowd behavior", { exact: true })).toHaveValue("mixed");
  await expect(page.locator("#stadium-speed-summary")).not.toContainText("1.20–1.20");
  await page.getByLabel("Spectators", { exact: true }).fill("3");
  await page.getByLabel("Starting seats", { exact: true }).selectOption("lower-bowl");
  await page.getByLabel("Crowd behavior", { exact: true }).selectOption("uniform");
  await expect(page.locator("#stadium-speed-summary")).toContainText("1.20–1.20");
  const seats = await page.locator("#stadium-crowd-agents circle").evaluateAll(circles => circles.map(c => [c.getAttribute("cx"), c.getAttribute("cy")]));
  await page.getByText("Inspect & edit an individual", { exact: true }).click();
  await page.getByLabel("Spectator", { exact: true }).selectOption("0");
  await page.getByLabel("Age (years)", { exact: true }).fill("72");
  await page.getByLabel("Height (cm)", { exact: true }).fill("160");
  await page.getByLabel("Weight (kg)", { exact: true }).fill("80");
  await page.getByLabel("Response delay (s)", { exact: true }).fill("10");
  await page.getByLabel("Speed override (m/s, optional)", { exact: true }).fill("0.6");
  await page.getByRole("button", { name: "Apply person profile", exact: true }).click();
  await expect(page.locator("#stadium-person-message")).toContainText("applied");
  await expect(page.locator("#stadium-person-status")).toContainText("preferred 0.60 m/s");
  await expect(page.locator("#stadium-speed-summary")).toContainText("0.60–1.20");
  const first = page.locator('#stadium-crowd-agents [data-person="0"]');
  const initialX = await first.getAttribute("cx"), initialY = await first.getAttribute("cy");
  await page.getByRole("button", { name: "Start stadium run", exact: true }).click();
  await expect.poll(async () => parseFloat(await page.locator("#stadium-run-time").innerText())).toBeGreaterThan(1);
  await expect(page.getByLabel("Age (years)", { exact: true })).toBeDisabled();
  await expect(first).toHaveAttribute("cx", initialX!); await expect(first).toHaveAttribute("cy", initialY!);
  await page.getByRole("button", { name: "Pause", exact: true }).click();
  await expect(page.getByLabel("Age (years)", { exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Reset crowd", exact: true }).click();
  await expect(page.getByLabel("Age (years)", { exact: true })).toHaveValue("35");
  await expect(page.locator("#stadium-speed-summary")).toContainText("1.20–1.20");
  await page.getByLabel("Crowd behavior", { exact: true }).selectOption("mixed");
  expect(await page.locator("#stadium-crowd-agents circle").evaluateAll(circles => circles.map(c => [c.getAttribute("cx"), c.getAttribute("cy")]))).toEqual(seats);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel("Spectator", { exact: true }).selectOption("2");
  await expect(page.locator("#stadium-person-status")).toContainText("Spectator 3");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("stadium-individual-profile-mobile.png"), fullPage: true });
  expect(errors).toEqual([]);
});
